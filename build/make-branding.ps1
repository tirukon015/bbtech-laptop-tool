<#
.SYNOPSIS
  Generates all derived branding assets from the official master logo.

.DESCRIPTION
  Master (never modified): src\BBTech.LaptopTool\Assets\Branding\logo-master.png  (1254x1254)

  Derived (regenerated by this script):
    logo-tile-256.png   full logo, rounded corners, transparent outside the tile (header, About)
    logo-tile-512.png   same, larger (home screen on big displays)
    splash.png          logo tile for the instant start-up splash (transparent corners, soft shadow)
    ..\bbtech.ico       Windows icon: 256/128/64 = full logo tile; 48/32/24/16 = the "bb tech"
                        screen area of the same logo (the full artwork is unreadable at tiny sizes)

  The master's background is a soft blue gradient that blends into the logo's own blue glow, so a
  pixel-accurate background cut-out would damage the logo. "Transparent" variants therefore keep the
  artwork intact and make only the area outside a rounded tile transparent. Proportions are never
  changed (square in, square out, high-quality bicubic resampling).
#>
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$dir = Join-Path $PSScriptRoot '..\src\BBTech.LaptopTool\Assets\Branding'
$master = [System.Drawing.Image]::FromFile((Resolve-Path (Join-Path $dir 'logo-master.png')))

function New-RoundedPath([float]$x, [float]$y, [float]$size, [float]$radius) {
    $p = New-Object System.Drawing.Drawing2D.GraphicsPath
    $d = $radius * 2
    $p.AddArc($x, $y, $d, $d, 180, 90)
    $p.AddArc($x + $size - $d, $y, $d, $d, 270, 90)
    $p.AddArc($x + $size - $d, $y + $size - $d, $d, $d, 0, 90)
    $p.AddArc($x, $y + $size - $d, $d, $d, 90, 90)
    $p.CloseFigure()
    return $p
}

# Render a square region of the master into a rounded tile of $size px (transparent corners).
function New-Tile([int]$size, [System.Drawing.Rectangle]$src, [float]$radiusRatio = 0.18, [int]$pad = 0, [switch]$Shadow) {
    $bmp = New-Object System.Drawing.Bitmap $size, $size, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = 'AntiAlias'; $g.InterpolationMode = 'HighQualityBicubic'; $g.PixelOffsetMode = 'HighQuality'; $g.CompositingQuality = 'HighQuality'
    $g.Clear([System.Drawing.Color]::Transparent)
    $inner = $size - 2 * $pad
    if ($Shadow) {
        for ($i = 6; $i -ge 1; $i--) {
            $sp = New-RoundedPath ($pad - $i + 2) ($pad - $i + 6) ($inner + 2 * $i - 4) ($inner * $radiusRatio + $i)
            $g.FillPath((New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(10, 0, 20, 60))), $sp)
        }
    }
    $path = New-RoundedPath $pad $pad $inner ([Math]::Max(1, $inner * $radiusRatio))
    $g.SetClip($path)
    $g.DrawImage($master, (New-Object System.Drawing.Rectangle $pad, $pad, $inner, $inner), $src, [System.Drawing.GraphicsUnit]::Pixel)
    $g.Dispose()
    return $bmp
}

$full = New-Object System.Drawing.Rectangle 0, 0, $master.Width, $master.Height
# Square around the "bb tech" laptop screen (keeps the logo's own colours and letterforms).
$mark = New-Object System.Drawing.Rectangle 340, 255, 560, 560
# Tighter square around the "bb" letters for 16/24 px.
$bb = New-Object System.Drawing.Rectangle 385, 280, 490, 490

foreach ($s in 256, 512) {
    $t = New-Tile $s $full
    $t.Save((Join-Path $dir "logo-tile-$s.png"), [System.Drawing.Imaging.ImageFormat]::Png); $t.Dispose()
}
$splash = New-Tile 420 $full 0.16 18 -Shadow
$splash.Save((Join-Path $dir 'splash.png'), [System.Drawing.Imaging.ImageFormat]::Png); $splash.Dispose()

# Multi-resolution ICO with PNG-compressed entries.
$sizes = 256, 128, 64, 48, 32, 24, 16
$pngs = foreach ($s in $sizes) {
    $src = if ($s -ge 64) { $full } elseif ($s -ge 32) { $mark } else { $bb }
    $ratio = if ($s -ge 64) { 0.18 } else { 0.22 }
    $b = New-Tile $s $src $ratio
    $ms = New-Object System.IO.MemoryStream
    $b.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png); $b.Dispose()
    , $ms.ToArray()
}
$ico = Join-Path $dir '..\bbtech.ico'
$fs = [System.IO.File]::Create($ico)
$bw = New-Object System.IO.BinaryWriter $fs
$bw.Write([UInt16]0); $bw.Write([UInt16]1); $bw.Write([UInt16]$sizes.Count)
$offset = 6 + 16 * $sizes.Count
for ($i = 0; $i -lt $sizes.Count; $i++) {
    $s = $sizes[$i]; $len = $pngs[$i].Length; $dim = if ($s -ge 256) { 0 } else { $s }
    $bw.Write([byte]$dim); $bw.Write([byte]$dim); $bw.Write([byte]0); $bw.Write([byte]0)
    $bw.Write([UInt16]1); $bw.Write([UInt16]32); $bw.Write([UInt32]$len); $bw.Write([UInt32]$offset)
    $offset += $len
}
foreach ($p in $pngs) { $bw.Write($p) }
$bw.Close()

# Preview sheet for checking small icon sizes (not shipped).
$sheet = New-Object System.Drawing.Bitmap 700, 280
$g = [System.Drawing.Graphics]::FromImage($sheet); $g.Clear([System.Drawing.Color]::White)
$x = 10
for ($i = 0; $i -lt $sizes.Count; $i++) {
    $img = [System.Drawing.Image]::FromStream((New-Object System.IO.MemoryStream (, $pngs[$i])))
    $g.DrawImage($img, $x, 10, $img.Width, $img.Height); $x += $img.Width + 10
}
$g.Dispose()
$sheet.Save((Join-Path $PSScriptRoot '..\artifacts\icon-preview.png'), [System.Drawing.Imaging.ImageFormat]::Png) 2>$null
$master.Dispose()
Write-Host "Branding assets written to $dir"

